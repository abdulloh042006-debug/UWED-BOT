export function langFromCode(code) {
  const c = String(code || '').toLowerCase();
  if (!c) return 'uz';
  if (c.startsWith('uz')) return 'uz';
  if (/^(ru|kk|ky|tg|be|uk|az|hy|ka|tk)/.test(c)) return 'ru';
  return 'en';
}
